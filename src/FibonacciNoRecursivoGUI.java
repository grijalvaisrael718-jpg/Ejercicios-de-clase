    public static double fibonacci(double n) {
        if (n == 0) {
            return 0;
        }
        if (n == 1) {
            return 1;
        }
        int anterior = 0;
        int siguente = 0;
        int actual = 1;
        for (int i = 2; i <= n; i++) {
            siguente = anterior + actual;
            anterior = actual;
            actual = siguente;
        }
        return actual;
    }
